export type IconName = keyof typeof iconRegistry;

type AppIconProps = {
    name: IconName | string;
    size?: number | string;
    weight?: IconProps['weight'];
    className?: string;
    style?: CSSProperties;
    label?: string;
};

export default function Icon({
    name,
    size = 20,
    weight = 'duotone',
    className,
    style,
    label,
}: AppIconProps) {
    const Component = iconRegistry[name as IconName] ?? CircleNotch;
    return (
        <Component
            size={size}
            weight={weight}
            className={className}
            style={style}
            aria-hidden={label ? undefined : true}
            aria-label={label}
        />
    );
}
